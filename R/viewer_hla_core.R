# HLA core handoff to the Viewer -------------------------------------------

## The HLA & TCR Motifs module calls the pure HLA core (R/hla_*.R) by bare
## name, and inst/viewer/hla_tcr_motifs/core_shim.R binds it into the module
## scope. Every object those files define carries an hla_ / HLA_ prefix
## (test-hla-app-contract.R pins this against the R/ sources), so the prefix
## selects the core from the namespace without a hand-maintained list.
.viewerHLACore <- function() {
  ns <- topenv(environment())
  names <- ls(ns, all.names = TRUE, pattern = "^[.]?(hla|HLA)_")
  mget(names, envir = ns)
}

## A standalone bundle never loads the package, so createShinyApp() writes the
## core into the bundle as plain source. Functions are deparsed without their
## namespace environment; the shim's sys.source() gives them the module scope.
.viewerHLACoreSource <- function() {
  core <- .viewerHLACore()
  definitions <- lapply(names(core), function(name) {
    value <- deparse(core[[name]])
    value[[1L]] <- paste(name, "<-", value[[1L]])
    c("", value)
  })
  c(
    "## Generated by createShinyApp() from the HLA core in the package R/",
    "## directory. Do not edit; rebuild the app instead.",
    unlist(definitions)
  )
}
